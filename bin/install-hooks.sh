#!/usr/bin/env bash
# Install the in-tree git hooks (one-time per clone; idempotent).
#
# Points git at bin/git-hooks/ (version-controlled, so every clone gets the
# same SBOM-staleness pre-commit check, #136).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
chmod +x bin/git-hooks/* 2>/dev/null || true

# WHY: core.hooksPath is local > global in git's precedence, so setting it
# here unconditionally would silently disable a box-wide global core.hooksPath
# some clones run (a fleet-wide push guard installed for every repo on the
# box). On a box with no global hooks path that's harmless; on a box with one,
# it is a safety regression, not a tradeoff. A global dispatcher of that kind
# already chains to "$(git rev-parse --git-common-dir)/hooks/<name>" when that
# file exists and is executable, so a chaining shim there activates this
# repo's hooks without ever touching core.hooksPath.
global_hooks_path=$(git config --global --get core.hooksPath 2>/dev/null || true)

if [ -n "$global_hooks_path" ]; then
    common_dir=$(git rev-parse --git-common-dir)
    mkdir -p "$common_dir/hooks"
    for hook in bin/git-hooks/*; do
        [ -f "$hook" ] || continue
        name=$(basename "$hook")
        shim="$common_dir/hooks/$name"
        # WHY resolved at RUN time via `git rev-parse --show-toplevel`, not baked in
        # at install time: git-common-dir/hooks/ is shared across every worktree of
        # this clone, so a shim written from one worktree must still resolve to
        # whichever worktree's own bin/git-hooks/$name is invoking it.
        cat > "$shim" <<SHIM
#!/usr/bin/env bash
# Generated by bin/install-hooks.sh — chains the global core.hooksPath
# dispatcher to this repo's own bin/git-hooks/$name without setting
# core.hooksPath locally. Re-run install-hooks.sh to refresh.
set -euo pipefail
exec "\$(git rev-parse --show-toplevel)/bin/git-hooks/$name" "\$@"
SHIM
        chmod +x "$shim"
    done
    echo "git hooks installed: chaining shim(s) in $common_dir/hooks/ (global core.hooksPath=$global_hooks_path preserved)"
else
    git config core.hooksPath bin/git-hooks
    echo "git hooks installed: core.hooksPath=bin/git-hooks (pre-commit)"
fi
